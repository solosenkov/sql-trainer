def main() -> None:
    if DB_PATH.exists():
        DB_PATH.unlink()
    con = sqlite3.connect(DB_PATH)
    try:
        # Применяем схему
        con.executescript(SCHEMA_PATH.read_text(encoding="utf-8"))

        con.executemany(
            "INSERT INTO products (id, name, category, price, stock, created_at) VALUES (?, ?, ?, ?, ?, ?)",
            PRODUCTS,
        )
        con.executemany(
            "INSERT INTO orders (id, product_id, quantity, order_date, customer_name) VALUES (?, ?, ?, ?, ?)",
            ORDERS,
        )
        con.executemany(
            "INSERT INTO employees (id, name, department, salary, hire_date) VALUES (?, ?, ?, ?, ?)",
            EMPLOYEES,
        )
        con.executemany(
            "INSERT INTO categories (id, name, description) VALUES (?, ?, ?)",
            CATEGORIES,
        )
        con.executemany(
            "INSERT INTO customers (id, name, email, city, registered_at) VALUES (?, ?, ?, ?, ?)",
            CUSTOMERS,
        )
        con.executemany(
            "INSERT INTO reviews (id, product_id, customer_id, rating, review_text, created_at) VALUES (?, ?, ?, ?, ?, ?)",
            REVIEWS,
        )
        con.executemany(
            """INSERT INTO exercises
               (level, order_in_level, title, theory, task_description, hint, expected_sql, expected_result_description, is_active)
               VALUES (?, ?, ?, ?, ?, ?, ?, ?, 1)""",
            EXERCISES,
        )
        con.commit()

        # Проверка: каждый expected_sql выполняется и возвращает >= 1 строки
        cur = con.cursor()
        # Связность новых таблиц: категории покрывают все products.category,
        # клиенты покрывают все orders.customer_name, отзывы ссылаются на живых.
        prod_cats = {r[0] for r in cur.execute("SELECT DISTINCT category FROM products")}
        dict_cats = {r[0] for r in cur.execute("SELECT name FROM categories")}
        assert prod_cats <= dict_cats, f"Категории без описания: {prod_cats - dict_cats}"
        order_names = {r[0] for r in cur.execute("SELECT DISTINCT customer_name FROM orders")}
        cust_names = {r[0] for r in cur.execute("SELECT name FROM customers")}
        assert order_names <= cust_names, f"Клиенты без карточки: {order_names - cust_names}"
        orphans = cur.execute(
            "SELECT COUNT(*) FROM reviews r "
            "LEFT JOIN products p ON p.id = r.product_id "
            "LEFT JOIN customers c ON c.id = r.customer_id "
            "WHERE p.id IS NULL OR c.id IS NULL"
        ).fetchone()[0]
        assert orphans == 0, "Есть отзывы на несуществующие товары/клиентов"
        for t, expected in (("categories", 3), ("customers", 10), ("reviews", 18)):
            cnt = cur.execute(f"SELECT COUNT(*) FROM {t}").fetchone()[0]
            assert cnt == expected, f"В {t} ожидалось {expected} строк, найдено {cnt}"
        rows = cur.execute(
            "SELECT id, level, order_in_level, expected_sql FROM exercises ORDER BY id"
        ).fetchall()
        assert len(rows) == 45, f"Ожидалось 45 заданий, найдено {len(rows)}"
        ok = 0
        for ex_id, level, order_in_level, sql in rows:
            try:
                result = cur.execute(sql).fetchall()
            except Exception as e:
                print(f"FAIL #{ex_id} (L{level}.{order_in_level}): {e}\n  SQL: {sql}",
                      file=sys.stderr)
                sys.exit(1)
            if not result:
                print(f"FAIL #{ex_id} (L{level}.{order_in_level}): запрос вернул 0 строк\n  SQL: {sql}",
                      file=sys.stderr)
                sys.exit(1)
            ok += 1
        print(f"OK: {ok}/45")
    finally:
        con.close()


if __name__ == "__main__":
    main()
